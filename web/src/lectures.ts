/** Original lectures. The shape follows a short lesson: what it is, the command, an example. */

import type { LessonBody } from "./lessonBodies";

function talk(prompt: string, syntax: string, paragraphs: string[]): LessonBody {
  const reading =
    paragraphs.length >= 6
      ? paragraphs
      : [
          ...paragraphs,
          "Команда в рамке — рабочий пример. Её можно перенести в поле и выполнить: строки ответа появятся таблицей. Дальше в ней меняют столбцы и условие, чтобы получить нужные строки.",
          "В попытку уходит одна команда. Несколько команд через точку с запятой база не примет. Имена берите из шапки таблицы. Текст пишут в одинарных кавычках, числа — без кавычек. Каждая попытка снова видит исходные строки.",
        ];
  return { prompt, syntax, paragraphs: reading };
}

